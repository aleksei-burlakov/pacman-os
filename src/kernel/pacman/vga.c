void fb_draw_char(int px, int py, char c, uint8_t color)
{
    const uint8_t* glyph = font8x8_basic[(int)c];

    for (int row = 0; row < 8; row++)
    {
        uint8_t bits = glyph[row];
        for (int col = 0; col < 8; col++)
        {
            if (bits & (1 << (7 - col)))
                fb_put_pixel(px + col, py + row, color);
        }
    }
}

void fb_draw_text(int tile_x, int tile_y, const char* s, uint8_t color)
{
    int px = tile_x * TILE_W;
    int py = tile_y * TILE_H;

    while (*s) {
        fb_draw_char(px, py, *s, color);
        px += 8; // фиксированная ширина символа
        s++;
    }
}